  const glyph = (ch) => G[ch] || G[ch.toUpperCase()] || G[' '];
  /** Width of text in dot columns (1 blank column between characters). */
  function cols(text) { let w = 0; for (const ch of text) w += glyph(ch)[0].length + 1; return Math.max(0, w - 1); }

  /**
   * Draw text as a dot matrix. x,y = top-left in px, pitch = px per dot.
   * Unlit dots in each character cell glow faintly, like a real display.
   */
  function draw(g, text, x, y, pitch, on, off) {
    const r = pitch * 0.38;
    let cx = x;
    const lit = [];
    for (const ch of text) {
      const rows = glyph(ch);
      const w = rows[0].length;
      if (off) g.fillStyle = off;
      for (let ry = 0; ry < 7; ry++) {
        for (let rx = 0; rx < w; rx++) {
          const px = cx + rx * pitch + pitch / 2, py = y + ry * pitch + pitch / 2;
          if (rows[ry][rx] === '1') lit.push(px, py);
          else if (off) { g.beginPath(); g.arc(px, py, r, 0, 6.283); g.fill(); }
        }
      }
      cx += (w + 1) * pitch;
    }
    // halo then crisp dots
    g.fillStyle = on;
    g.globalAlpha = 0.18;
    for (let i = 0; i < lit.length; i += 2) { g.beginPath(); g.arc(lit[i], lit[i + 1], pitch * 0.85, 0, 6.283); g.fill(); }
    g.globalAlpha = 1;
    for (let i = 0; i < lit.length; i += 2) { g.beginPath(); g.arc(lit[i], lit[i + 1], r * 1.08, 0, 6.283); g.fill(); }
    return cx - x;
  }

  root.LCD = { draw, cols };
